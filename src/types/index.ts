// ======================================================
// 型定義ファイル
// このファイルにサイト全体で使う「型」をまとめておく。
// 型とは「このデータはどんな形をしているか」を
// TypeScript に伝えるための設計図のようなもの。
// ======================================================

// -------------------------------------------
// アプリの種別
// app   → インタラクティブな学習アプリ
// print → プリント生成ツール
// tool  → 授業支援ツール（タイマー・作戦ボードなど）
// -------------------------------------------
export type AppType = "app" | "print" | "tool"

// -------------------------------------------
// 対象学年
// 数字は小学1〜6年、それ以外は文字列で表す
// -------------------------------------------
export type Grade = 1 | 2 | 3 | 4 | 5 | 6 | "中学" | "高校" | "先生向け" | "全学年"

// -------------------------------------------
// アプリ1件分のデータ構造
// src/data/apps.ts の配列の中身はこの型に合わせる
// -------------------------------------------
export type AppItem = {
  /** URLに使う一意のID（例："tashizan"）*/
  id: string

  /** 表示名（日本語）*/
  title: string

  /** アプリの説明文（トップページのカードに表示）。短く・小学生向け・漢字控えめ */
  description: string

  /**
   * SEO・AIO 用の長文説明（省略可）
   * - Google検索結果のスニペット・OGP・JSON-LD（AI参照元）に使われる
   * - 「何ができるか」「特徴」を具体的に書く（30〜80文字程度）
   * - 省略時は description にフォールバック（短くてもよい・地味なアプリ向け）
   * - 検索流入を取りに行きたいフラッグシップアプリで書く
   */
  seoDescription?: string

  /** 対象学年（複数の学年に属せる）*/
  grades: Grade[]

  /** 教科（複数可）*/
  subjects: string[]

  /** タグ（検索・絞り込みに使う）*/
  tags: string[]

  /** 種別：app / print / tool */
  type: AppType

  /** アプリページのパス（例："/tashizan"）*/
  path: string

  /** true のとき、ポータルに表示しない（未実装・開発中アプリ）*/
  disabled?: boolean
}
