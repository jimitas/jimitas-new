// ======================================================
// 数値の表示（円の面積と円周のひみつ）
//
// 要件 §5.2：表示は小数第2位に丸める（12.598 → 12.60）。末尾の 0 は落とさない
// （共通の formatFixed は 12.6 と出すので使わない。記録表で桁がそろわなくなるため）。
// 半径・太さのように決まった値をそのまま出すときは、共通の formatNumber（1.875 → "1.875"）を使う。
// ======================================================

import { MINUS } from "@/lib/graph/format"

/** 小数第2位で丸め、末尾の 0 も残す（12.598 → "12.60"、2 → "2.00"）。負の数は「−」、−0 は "0.00" */
export function format2(v: number): string {
  if (!Number.isFinite(v)) return "—"
  // toFixed は2進数の誤差をそのまま丸めるので、11.78 × 0.25（= 2.945、内部では 2.94499…）を "2.94" にしてしまう。
  // 画面の式を電卓で確かめた値（2.95）と合うよう、ごくわずかに外向きに寄せてから四捨五入する（十進数の四捨五入どおり）
  const cents = Math.sign(v) * Math.round(Math.abs(v) * 100 * (1 + 1e-12))
  const s = (cents / 100).toFixed(2)
  return s === "-0.00" ? "0.00" : s.replace("-", MINUS)
}
